    public static void render(float[] mesh, PoseStack.Pose pose, VertexConsumer buffer, int light, int overlay, int color) {
        Matrix4f matrix = pose.pose();
        Matrix3f normalMatrix = pose.normal();
        Vector3f position = new Vector3f();
        Vector3f normal = new Vector3f();
        for (int i = 0; i < mesh.length; i += 8) {
            matrix.transformPosition(mesh[i] / 16.0F, mesh[i + 1] / 16.0F, mesh[i + 2] / 16.0F, position);
            normalMatrix.transform(mesh[i + 5], mesh[i + 6], mesh[i + 7], normal).normalize();
            buffer.addVertex(position.x(), position.y(), position.z(), color, mesh[i + 3], mesh[i + 4], overlay, light, normal.x(), normal.y(), normal.z());
        }
    }
